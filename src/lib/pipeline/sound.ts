import { db } from "@/lib/db";
import { mapSettled } from "@/lib/async";
import { DEFAULT_MUSIC, SOUND_EFFECTS, type SoundEffectKey } from "@/lib/constants";
import { musicCost, soundEffectCost } from "@/lib/costs/pricing";
import { assertWithinBudget, recordCost, type CostContext } from "@/lib/costs/record";
import { getPricing, type AudioMix } from "@/lib/settings";
import { paths, uploadAsset } from "@/lib/storage";
import type { SoundProvider } from "@/lib/providers/sound";

/** Seconds generated per effect: loops run under a whole shot, one-shots play once at its start. */
const EFFECT_SECONDS = { loop: 6, once: 3 };

export type Soundtrack = {
  music: { url: string } | null;
  effects: Partial<Record<SoundEffectKey, { url: string; loop: boolean }>>;
};

type Generated = { mp3: Buffer; model: string; costUsd: number; usage: Record<string, unknown> };

/**
 * The library asset stored under `key`, generated the first time it is needed.
 * Sound is a finishing touch: any failure (provider, plan, budget) is logged
 * and the video renders without it.
 */
async function libraryAsset(
  key: string,
  meta: { kind: "MUSIC" | "SFX"; name: string; estimateUsd: number },
  generate: (() => Promise<Generated>) | null,
  cost: CostContext,
): Promise<string | null> {
  try {
    const existing = await db.audioAsset.findUnique({ where: { key } });
    if (existing) return existing.url;
    if (!generate) return null;
    await assertWithinBudget(cost, meta.estimateUsd);
    const made = await generate();
    await recordCost(cost, { provider: "ELEVENLABS", model: made.model, operation: `library-audio-${key}`, usage: made.usage, costUsd: made.costUsd, estimated: true });
    const uploaded = await uploadAsset(paths.libraryAudio(key), made.mp3, "audio/mpeg");
    const row = await db.audioAsset
      .create({
        data: { key, kind: meta.kind, name: meta.name, url: uploaded.url, source: `ElevenLabs (${made.model}), generated by the studio`, license: "Generated with the studio's ElevenLabs account; usable under its plan's terms" },
      })
      // Another render made it at the same moment: use theirs.
      .catch(async () => db.audioAsset.findUniqueOrThrow({ where: { key } }));
    return row.url;
  } catch (err) {
    console.warn(`Skipping ${key}: ${String((err as Error)?.message ?? err)}`);
    return null;
  }
}

/** The music and per-shot sound effects for a render. Without `sound`, only audio already in the library is used. */
export async function resolveSoundtrack(input: { soundEffects: string[]; mix: AudioMix; cost: CostContext; sound?: SoundProvider }): Promise<Soundtrack> {
  const pricing = await getPricing();
  const { sound } = input;
  const keys = [...new Set(input.soundEffects)].filter((k): k is SoundEffectKey => k in SOUND_EFFECTS);

  const music = async (): Promise<string | null> => {
    if (!input.mix.musicEnabled) return null;
    if (input.mix.musicAssetId) return (await db.audioAsset.findUnique({ where: { id: input.mix.musicAssetId } }))?.url ?? null;
    const costUsd = musicCost(pricing, DEFAULT_MUSIC.lengthMs);
    return libraryAsset(
      DEFAULT_MUSIC.key,
      { kind: "MUSIC", name: DEFAULT_MUSIC.name, estimateUsd: costUsd },
      sound ? async () => ({ ...(await sound.music({ prompt: DEFAULT_MUSIC.prompt, lengthMs: DEFAULT_MUSIC.lengthMs })), costUsd, usage: { lengthMs: DEFAULT_MUSIC.lengthMs } }) : null,
      input.cost,
    );
  };

  const [musicUrl, effectUrls] = await Promise.all([
    music(),
    mapSettled(keys, 3, (key) => {
      const fx = SOUND_EFFECTS[key];
      const seconds = fx.loop ? EFFECT_SECONDS.loop : EFFECT_SECONDS.once;
      const costUsd = soundEffectCost(pricing, seconds);
      return libraryAsset(
        `sfx:${key}`,
        { kind: "SFX", name: `${fx.label} (generated)`, estimateUsd: costUsd },
        sound ? async () => ({ ...(await sound.effect({ prompt: fx.prompt, durationSeconds: seconds, loop: fx.loop })), costUsd, usage: { seconds, loop: fx.loop } }) : null,
        input.cost,
      );
    }),
  ]);

  const effects: Soundtrack["effects"] = {};
  keys.forEach((key, i) => {
    const r = effectUrls[i];
    if (r.status === "fulfilled" && r.value) effects[key] = { url: r.value, loop: SOUND_EFFECTS[key].loop };
  });
  return { music: musicUrl ? { url: musicUrl } : null, effects };
}
